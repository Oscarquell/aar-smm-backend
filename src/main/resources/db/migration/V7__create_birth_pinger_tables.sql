CREATE TABLE birthday_people (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL,
    phone VARCHAR(32),
    birth_date DATE NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX birthday_people_active_month_day_idx
    ON birthday_people (EXTRACT(MONTH FROM birth_date), EXTRACT(DAY FROM birth_date))
    WHERE active = TRUE;
CREATE UNIQUE INDEX birthday_people_name_birth_date_unique
    ON birthday_people (LOWER(BTRIM(full_name)), birth_date);

CREATE TABLE birthday_message_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    birthday_person_id BIGINT NOT NULL REFERENCES birthday_people(id),
    birthday_year INTEGER NOT NULL,
    generated_text TEXT,
    status VARCHAR(20) NOT NULL,
    sent_at TIMESTAMPTZ,
    error_message VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT birthday_message_history_status_allowed CHECK (status IN ('PROCESSING', 'SENT', 'FAILED')),
    CONSTRAINT birthday_message_history_person_year_unique UNIQUE (birthday_person_id, birthday_year)
);
