CREATE TABLE blocked_ip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip INET NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX blocked_ip_active_ip_unique_idx
    ON blocked_ip (ip)
    WHERE deleted = FALSE;

CREATE INDEX blocked_ip_active_created_at_idx
    ON blocked_ip (created_at)
    WHERE deleted = FALSE;
